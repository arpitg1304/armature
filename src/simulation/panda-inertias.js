var pandaDynamicsModel = PANDA_INERTIAS;
function applyLinkInertia(s, e, t, n, { fixed: r = !1 } = {}) {
  let i = s.T,
    c = PANDA_INERTIAS.links[t],
    o = e.body;
  if (!c) throw Error("Missing physical link " + t);
  let h = new i.Vector3(...c.com),
    d = new i.Quaternion(...c.principalQuaternion),
    f = e.link.getWorldQuaternion(new i.Quaternion()),
    p = e.link.localToWorld(h.clone());
  ((e.offset = h),
    (e.principalRotation = d),
    (e.physicalLink = t),
    o.position.set(...p.toArray()));
  let b = f.multiply(d);
  (o.quaternion.set(b.x, b.y, b.z, b.w),
    (o.type = r ? n.Body.STATIC : n.Body.DYNAMIC),
    (o.mass = r ? 0 : c.mass));
  for (let O of o.shapes.slice()) o.removeShape(O);
  let H = d.clone().invert(),
    P = (O) => new i.Vector3(...O).sub(h).applyQuaternion(H),
    X = (O) => new n.Vec3(O.x, O.y, O.z);
  for (let O of c.shapes)
    if (O.type === "convex") {
      let D = O.vertices
          .reduce((g, q) => g.add(new i.Vector3(...q)), new i.Vector3())
          .multiplyScalar(1 / O.vertices.length),
        L = O.vertices.map((g) =>
          X(new i.Vector3(...g).sub(D).applyQuaternion(H)),
        );
      o.addShape(
        new n.ConvexPolyhedron({ vertices: L, faces: O.faces }),
        X(P(D.toArray())),
      );
    } else {
      let D = H.clone().multiply(new i.Quaternion(...O.quaternion));
      o.addShape(
        new n.Box(new n.Vec3(...O.halfExtents)),
        X(P(O.position)),
        new n.Quaternion(D.x, D.y, D.z, D.w),
      );
    }
  let y = o.updateMassProperties.bind(o);
  return (
    (o.updateMassProperties = () => {
      (y(),
        o.inertia.set(...c.principalInertia),
        o.invInertia.set(
          ...c.principalInertia.map((O) => (o.mass > 0 ? 1 / O : 0)),
        ),
        o.updateInertiaWorld(!0));
    }),
    o.updateMassProperties(),
    o.updateBoundingRadius(),
    (o.aabbNeedsUpdate = !0),
    o.previousPosition.copy(o.position),
    o.previousQuaternion.copy(o.quaternion),
    (o.linearDamping = 0.03),
    (o.angularDamping = 0.08),
    c
  );
}
